using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AvaloniaStyles.Generators;

internal readonly record struct ParsedIcon(
    string Name,
    double X,
    double Y,
    double Width,
    double Height,
    string PathData,
    string? Error);

[Generator]
public class IconSourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var icons = context.AdditionalTextsProvider
            .Where(f => f.Path.EndsWith(".svg", StringComparison.OrdinalIgnoreCase))
            .Select(ParseIcon);

        context.RegisterSourceOutput(icons.Collect(), Generate);
    }

    private static ParsedIcon ParseIcon(AdditionalText file, CancellationToken ct)
    {
        var name = Path.GetFileNameWithoutExtension(file.Path);
        try
        {
            var content = file.GetText(ct)?.ToString() ?? "";
            var (vb, path) = SvgParser.Parse(content);
            return new ParsedIcon(name, vb.X, vb.Y, vb.Width, vb.Height, path, Error: null);
        }
        catch (Exception ex)
        {
            return new ParsedIcon(name, 0, 0, 0, 0, "", ex.Message);
        }
    }

    private static void Generate(SourceProductionContext ctx, ImmutableArray<ParsedIcon> icons)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by AvaloniaStyles.Generators.IconSourceGenerator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Avalonia;");
        sb.AppendLine("using Avalonia.Media;");
        sb.AppendLine();
        sb.AppendLine("namespace AvaloniaStyles.Generated;");
        sb.AppendLine();
        sb.AppendLine("public readonly record struct IconDefinition(Rect ViewBox, Geometry Geometry);");
        sb.AppendLine();
        sb.AppendLine("public static class IconCatalog");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly IReadOnlyDictionary<string, IconDefinition> All =");
        sb.AppendLine("        new Dictionary<string, IconDefinition>");
        sb.AppendLine("        {");

        foreach (var icon in icons.OrderBy(i => i.Name, StringComparer.Ordinal))
        {
            if (icon.Error is not null)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "ICN001",
                        "SVG parse error",
                        "Failed to parse {0}.svg: {1}",
                        "AvaloniaStyles.Generators",
                        DiagnosticSeverity.Error,
                        isEnabledByDefault: true),
                    Location.None,
                    icon.Name,
                    icon.Error));
                continue;
            }

            var key = EscapeStringLiteral(icon.Name);
            var pathLit = EscapeStringLiteral(icon.PathData);
            sb.AppendLine(
                $"            [\"{key}\"] = new(new Rect({F(icon.X)}, {F(icon.Y)}, {F(icon.Width)}, {F(icon.Height)}), Geometry.Parse(\"{pathLit}\")),");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("    public static Geometry? Get(string symbol) =>");
        sb.AppendLine("        All.TryGetValue(symbol, out var def) ? def.Geometry : null;");
        sb.AppendLine("}");

        ctx.AddSource("IconCatalog.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string EscapeStringLiteral(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string F(double v) =>
        v.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture);
}
