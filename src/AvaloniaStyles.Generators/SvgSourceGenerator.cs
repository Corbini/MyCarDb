using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AvaloniaStyles.Generators;

internal readonly record struct ParsedSvg(
    string Name,
    double X,
    double Y,
    double Width,
    double Height,
    ImmutableArray<SvgFigureData> Figures,
    string? Error);

[Generator]
public class SvgSourceGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var svgs = context.AdditionalTextsProvider
            .Where(f => f.Path.EndsWith(".svg", StringComparison.OrdinalIgnoreCase))
            .Select(ParseSvg);

        context.RegisterSourceOutput(svgs.Collect(), Generate);
    }

    private static ParsedSvg ParseSvg(AdditionalText file, CancellationToken ct)
    {
        string name = Path.GetFileNameWithoutExtension(file.Path);
        try
        {
            string content = file.GetText(ct)?.ToString() ?? "";
            var (vb, figures) = SvgParser.Parse(content);
            return new ParsedSvg(name, vb.X, vb.Y, vb.Width, vb.Height, figures.ToImmutableArray(), Error: null);
        }
        catch (Exception ex)
        {
            return new ParsedSvg(name, 0, 0, 0, 0, ImmutableArray<SvgFigureData>.Empty, ex.Message);
        }
    }

    private static void Generate(SourceProductionContext ctx, ImmutableArray<ParsedSvg> svgs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by AvaloniaStyles.Generators.SvgSourceGenerator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Avalonia;");
        sb.AppendLine("using Avalonia.Media;");
        sb.AppendLine();
        sb.AppendLine("namespace AvaloniaStyles.Generated;");
        sb.AppendLine();
        sb.AppendLine("public readonly record struct SvgFigure(Geometry Geometry, uint? FillArgb);");
        sb.AppendLine();
        sb.AppendLine("public readonly record struct SvgDefinition(Rect ViewBox, Geometry CombinedGeometry, IReadOnlyList<SvgFigure> Figures);");
        sb.AppendLine();
        sb.AppendLine("public static class SvgCatalog");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly IReadOnlyDictionary<string, SvgDefinition> All =");
        sb.AppendLine("        new Dictionary<string, SvgDefinition>");
        sb.AppendLine("        {");

        foreach (var svg in svgs.OrderBy(s => s.Name, StringComparer.Ordinal))
        {
            if (svg.Error is not null)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "SVG001",
                        "SVG parse error",
                        "Failed to parse {0}.svg: {1}",
                        "AvaloniaStyles.Generators",
                        DiagnosticSeverity.Error,
                        isEnabledByDefault: true),
                    Location.None,
                    svg.Name,
                    svg.Error));
                continue;
            }

            string key = EscapeStringLiteral(svg.Name);
            string combinedPath = EscapeStringLiteral(string.Join(" ", svg.Figures.Select(f => f.PathData)));

            sb.AppendLine($"            [\"{key}\"] = new(");
            sb.AppendLine($"                new Rect({F(svg.X)}, {F(svg.Y)}, {F(svg.Width)}, {F(svg.Height)}),");
            sb.AppendLine($"                Geometry.Parse(\"{combinedPath}\"),");
            sb.AppendLine("                new SvgFigure[]");
            sb.AppendLine("                {");
            foreach (var fig in svg.Figures)
            {
                string pathLit = EscapeStringLiteral(fig.PathData);
                string fillLit = fig.FillArgb is uint argb ? $"0x{argb:X8}u" : "null";
                sb.AppendLine($"                    new(Geometry.Parse(\"{pathLit}\"), {fillLit}),");
            }
            sb.AppendLine("                }),");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("    public static SvgDefinition? Get(string symbol) =>");
        sb.AppendLine("        All.TryGetValue(symbol, out var def) ? def : null;");
        sb.AppendLine("}");

        ctx.AddSource("SvgCatalog.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string EscapeStringLiteral(string s) =>
        s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string F(double v) =>
        v.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture);
}
